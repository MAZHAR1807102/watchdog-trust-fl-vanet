"""LaTeX rows for the main results table of Paper A (sign-flip and label-flip, low to high attacker share).

Reads ../experiments/{results, results_labelflip, results_lowshare}/*_summary.json (p_d = 0.5).
Prints the table body (paste into main.tex, tab:main) and the 0%-attacker cost check.
Usage: ~/miniforge3/bin/python3 make_tables.py [--write]   (--write: replace the body of tab:main in main.tex)
"""
import contextlib
import glob
import io
import sys
import json
import re
from pathlib import Path

import numpy as np

D = Path(__file__).resolve().parent / '../experiments'
FOLDERS = ['results', 'results_labelflip', 'results_lowshare']
RHOS = [0.1, 0.2, 0.3, 0.5, 0.7]
ATTACKS = ['sign_flip', 'label_flip']
ROWS = [('FedAvg', 'FedAvg'), ('Krum', 'Krum'), ('TrimmedMean', 'Trimmed mean'), ('Median', 'Median'),
        ('Krum+Bucket', 'Krum+Bucket'), ('Median+Bucket', 'Median+Bucket'), None,
        ('Trust-FLAD', 'TF'), ('Trust-FLAD+Krum', 'TF+Krum'), ('Trust-FLAD+Median', 'TF+Median'),
        ('Trust-FLAD+Krum+Bucket', 'TF+Krum+Bucket'), ('Trust-FLAD+Median+Bucket', 'TF+Median+Bucket')]


def load():
    runs = {}  # (attack, rho) -> list of results dicts
    for folder in FOLDERS:
        for f in glob.glob(str(D / folder / 'm*_d0.5_s*_summary.json')):
            j = json.load(open(f))
            if '_on' in j['csv'] or j['config'].get('poison_set') == 'decoupled':
                continue
            rho = float(re.search(r'/m([\d.]+)_d0\.5_s', j['csv']).group(1))
            runs.setdefault((j['config']['attack'], rho), []).append(j['results'])
    return runs


def mean(rs, method, key='f1'):
    v = [r[method][key] for r in rs if method in r and r[method].get(key) is not None]
    v = [x for x in v if x == x]  # drop NaN
    return np.mean(v) if v else None


def cell(x):
    return '--' if x is None else f'{x:.2f}'


runs = load()
buf = io.StringIO()
_ctx = contextlib.redirect_stdout(buf)
_ctx.__enter__()
cols = [(a, r) for a in ATTACKS for r in RHOS]
print('% n seeds per column:', ' '.join(str(len(runs.get(c, []))) for c in cols))
print('No-attack ceiling & ' + ' & '.join(cell(mean(runs.get(('none', r), []), 'FedAvg')) for _, r in cols) + r'\\')
print(r'\midrule')
for row in ROWS:
    if row is None:
        print(r'\midrule')
        continue
    m, label = row
    print(f'{label} & ' + ' & '.join(cell(mean(runs.get(c, []), m)) for c in cols) + r'\\')
print(r'\midrule')
for key, sym in [('beta', r'$\beta$'), ('gamma', r'$\gamma$')]:
    print(f'{sym} & ' + ' & '.join(cell(mean(runs.get(c, []), 'Trust-FLAD', key)) for c in cols) + r'\\')

_ctx.__exit__(None, None, None)
body = buf.getvalue()
print(body, end='')
if '--write' in sys.argv:
    tex = Path(__file__).resolve().parent / 'main.tex'
    t = tex.read_text()
    a, b = '%TABLE-BODY-BEGIN (generated by make_tables.py --write)\n', '%TABLE-BODY-END\n'
    i, j = t.index(a) + len(a), t.index(b)
    tex.write_text(t[:i] + body + t[j:])
    print('% wrote table body into main.tex')

# cost of the filter when nobody attacks (and at low shares without poisoning)
print('\n% Filter cost without poisoning (attack none): accuracy, F1, gamma, kept per round')
for rho in [0.0, 0.04, 0.1]:
    rs = runs.get(('none', rho), [])
    if not rs:
        continue
    out = [f'rho {rho:.2f} n={len(rs)}']
    for m in ['FedAvg', 'Median', 'Trust-FLAD', 'Trust-FLAD+Median', 'Trust-FLAD+Krum']:
        out.append(f"{m} acc {cell(mean(rs, m, 'accuracy'))} f1 {cell(mean(rs, m))}")
    out.append(f"gamma {cell(mean(rs, 'Trust-FLAD', 'gamma'))} kept {cell(mean(rs, 'Trust-FLAD', 'accepted_mean'))}")
    print('%  ' + ' | '.join(out))
